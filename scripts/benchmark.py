from __future__ import annotations

"""
Saurix Benchmark Harness

A single, parametrized script that measures indexing throughput, repeated
re-index runs (a straight redo, since there is no incremental cache), graph
size, and impact-query latency across a set of repositories. It produces one
markdown report in a single shape.

Usage:
    uv run scripts/benchmark.py
    uv run scripts/benchmark.py --repos pallets/flask,axios/axios
    uv run scripts/benchmark.py --out /tmp/bench.md
"""

import argparse
import os
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path
from time import perf_counter

from saurix.core.indexing import build_graph
from saurix.discovery import impact_of


@dataclass
class BenchResult:
    """One row of measured data for a single repository."""

    repo_name: str
    language: str
    total_files: int
    full_index_time: float
    reindex_time: float
    graph_size_kb: float
    query_latency_ms: float
    nodes: int
    edges: int


# (slug, clone URL, language hint, symbol probe for the impact query)
REPOS: list[tuple[str, str, str, str]] = [
    ("pallets/flask", "https://github.com/pallets/flask.git", "python", "flask.app:Flask"),
    ("axios/axios", "https://github.com/axios/axios.git", "typescript", "axios:Axios"),
    ("django/django", "https://github.com/django/django.git", "python", "django.db.models:Model"),
    ("facebook/react", "https://github.com/facebook/react.git", "typescript", "react:useState"),
    ("kubernetes/kubernetes", "https://github.com/kubernetes/kubernetes.git", "go", "k8s.io.kubernetes.pkg.kubelet:Kubelet"),
]


def ensure_clone(repos_dir: Path, slug: str, url: str) -> Path:
    """Clone (or reuse) a deep-one git checkout for a repository."""
    local_repo = repos_dir / slug.replace("/", "__")
    if local_repo.exists():
        return local_repo
    local_repo.parent.mkdir(parents=True, exist_ok=True)
    print(f"Cloning {url}...")
    command = ["git", "clone", "--depth", "1", url, str(local_repo)]
    completed = subprocess.run(command, capture_output=True, text=True, check=False)
    if completed.returncode != 0:
        raise RuntimeError(completed.stderr.strip() or completed.stdout.strip() or f"clone failed: {url}")
    return local_repo


def clear_bench_artifacts(repo_root: Path) -> None:
    """Remove leftover graph files so each run starts from a clean state."""
    bench_graph = repo_root / "tmp" / "saurix.graph.json"
    if bench_graph.exists():
        bench_graph.unlink()
    bench_tmp = repo_root / "tmp" / "bench"
    if bench_tmp.exists() and bench_tmp.is_dir():
        shutil.rmtree(bench_tmp)


def measure_repo(repo_root: Path, slug: str, lang: str, test_symbol: str, graphs_dir: Path) -> BenchResult:
    """Run the full index, a straight redo re-index, and an impact query."""
    clear_bench_artifacts(repo_root)

    # 1. Full index, persisted to a graph file.
    t0 = perf_counter()
    full = build_graph(repo_root)
    full_time = perf_counter() - t0

    graph_path = graphs_dir / f"{slug.replace('/', '_')}.json"
    full.graph.write_json(graph_path)
    graph_size = os.path.getsize(graph_path) / 1024
    stats = full.graph.stats()

    # 2. Straight redo re-index (no cache to replay).
    t1 = perf_counter()
    build_graph(repo_root)
    reindex_time = perf_counter() - t1

    # 3. Impact query latency on a found symbol.
    found = [n.id for n in full.graph.nodes.values() if test_symbol in n.id or test_symbol in n.name]
    query_latency = 0.0
    if found:
        t2 = perf_counter()
        impact_of(full.graph, found[0], depth=3)
        query_latency = (perf_counter() - t2) * 1000

    return BenchResult(
        repo_name=slug,
        language=lang,
        total_files=full.scanned_files,
        full_index_time=full_time,
        reindex_time=reindex_time,
        graph_size_kb=graph_size,
        query_latency_ms=query_latency,
        nodes=stats.get("nodes", 0),
        edges=stats.get("edges", 0),
    )


def generate_markdown(results: list[BenchResult]) -> str:
    """Render all measured repos into a single markdown report table."""
    lines = [
        "# Saurix Performance Benchmarks",
        "",
        "This report is automatically generated by `scripts/benchmark.py`.",
        "Re-index is a straight redo: there is no incremental cache to replay.",
        "",
        "| Repository | Language | Files | Full Index | Re-index | Speedup | Graph Size | Nodes | Edges | Density | Impact Query |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for r in results:
        speedup = round(r.full_index_time / r.reindex_time, 1) if r.reindex_time > 0 else 0.0
        density = round(r.edges / r.nodes, 2) if r.nodes > 0 else 0.0
        lines.append(
            f"| `{r.repo_name}` | {r.language} | {r.total_files} | {r.full_index_time:.2f}s | "
            f"{r.reindex_time:.2f}s | {speedup}x | {r.graph_size_kb:.1f} KB | {r.nodes} | {r.edges} | "
            f"{density} | {r.query_latency_ms:.1f} ms |"
        )
    lines.extend(["", "---", "*Benchmarks performed on: macOS / Apple Silicon.*"])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    """Run the benchmark harness and write the markdown report."""
    parser = argparse.ArgumentParser(prog="benchmark", description="Saurix benchmark harness")
    parser.add_argument(
        "--repos",
        default=None,
        help="Comma-separated slugs to benchmark (default: all repos)",
    )
    parser.add_argument(
        "--out",
        default="docs/benchmarks.md",
        help="Destination path for the markdown report",
    )
    args = parser.parse_args(argv)

    root = Path(__file__).resolve().parents[1]
    bench_root = root / "tmp" / "bench"
    repos_dir = bench_root / "repos"
    graphs_dir = bench_root / "graphs"
    repos_dir.mkdir(parents=True, exist_ok=True)
    graphs_dir.mkdir(parents=True, exist_ok=True)

    selected: set[str] = {s.strip() for s in args.repos.split(",")} if args.repos else set()
    targets = [entry for entry in REPOS if not selected or entry[0] in selected]

    results: list[BenchResult] = []
    for slug, url, lang, test_symbol in targets:
        print(f"--- Benchmarking {slug} ({lang}) ---")
        try:
            local_repo = ensure_clone(repos_dir, slug, url)
            result = measure_repo(local_repo, slug, lang, test_symbol, graphs_dir)
            results.append(result)
            print(
                f"Done. Files: {result.total_files}, Full: {result.full_index_time:.2f}s, "
                f"Re-index: {result.reindex_time:.2f}s, Query: {result.query_latency_ms:.1f}ms"
            )
        except Exception as exc:
            print(f"Failed to benchmark {slug}: {exc}")

    report = generate_markdown(results)
    out = (root / args.out) if not Path(args.out).is_absolute() else Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(f"\nReport generated at {out}")


if __name__ == "__main__":
    main()
